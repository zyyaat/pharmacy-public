LANGS = {"ar": AR, "en": EN, "fr": FR, "es": ES,
         **{k: {**EN, **v} for k, v in DERIVED.items()}}

fail = False
for lang, additions in LANGS.items():
    path = os.path.join(BASE, lang, "payments.json")
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    before = len(data)
    data.update(additions)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"{lang}: +{len(data) - before} keys -> {len(data)}")

# key parity check
ref = None
for lang in LANGS:
    with open(os.path.join(BASE, lang, "payments.json"), encoding="utf-8") as f:
        keys = set(json.load(f).keys())
    if ref is None:
        ref = keys
    elif keys != ref:
        print(f"PARITY FAIL {lang}: missing={sorted(ref - keys)[:5]} extra={sorted(keys - ref)[:5]}")
        fail = True
if not fail:
    print("KEY PARITY OK ×8")
sys.exit(1 if fail else 0)
